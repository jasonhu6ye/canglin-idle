/** 把字符画画到 canvas 上，供 Phaser 注册成纹理 */
export function paintSprite(rows: string[], scale = 1, swap: Record<string, string> = {}): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = 16 * scale;
  canvas.height = 16 * scale;
  const ctx = canvas.getContext('2d')!;
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const color = swap[row[x]] ?? PALETTE[row[x]];
      if (!color) continue;
      ctx.fillStyle = color;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  });
  return canvas;
}
