const KEY = 'canglin-news-seen';
type Fn = () => void;
const fns = new Set<Fn>();
export const openNews = () => fns.forEach((f) => f());

const closed = new Set<() => void>();
/** 更新公告关掉以后（或者这次本来就不弹）再弹别的，比如活动公告，免得两个弹窗叠在一起 */
export function onNewsClosed(f: () => void) {
  closed.add(f);
  return () => { closed.delete(f); };
}
export function newsPending() {
  try { return !!localStorage.getItem('canglin-guide-seen') && localStorage.getItem(KEY) !== NEWS[0].id; } catch { return false; }
}

export function News() {
  const [open, setOpen] = useState(() => {
    try {
      const seen = localStorage.getItem(KEY);
      // 新玩家（还没看过新手指引）不弹，直接记成已看
      if (!localStorage.getItem('canglin-guide-seen')) {
        localStorage.setItem(KEY, NEWS[0].id);
        return false;
      }
      return seen !== NEWS[0].id;
    } catch {
      return false;
    }
  });
  const [more, setMore] = useState(false);
  useEffect(() => {
    const f = () => { setOpen(true); setMore(false); };
    fns.add(f);
    return () => { fns.delete(f); };
  }, []);
  if (!open) return null;
  const close = () => {
    try { localStorage.setItem(KEY, NEWS[0].id); } catch { /* 存不了就算了 */ }
    setOpen(false);
    closed.forEach((f) => f());
  };
  const shown = more ? NEWS : NEWS.slice(0, 1);
  return (
    <div className="item-popup" onClick={close}>
      <div className="item-popup-body frame news" onClick={(e) => e.stopPropagation()}>
        <h2 className="gold">{tl('更新公告')}</h2>
        <div className="news-body">
          {shown.map((n) => (
            <section key={n.id}>
              <h3>{n.title} <small className="muted">{n.date}</small></h3>
              <ul>{n.lines.map((l) => <li key={l}>{l}</li>)}</ul>
            </section>
          ))}
        </div>
        <div className="go">
          {!more && NEWS.length > 1 && <button onClick={() => setMore(true)}>{tl('往期公告')}</button>}
          <button className="primary" onClick={close}>{tl('知道了')}</button>
        </div>
      </div>
    </div>
  );
}
